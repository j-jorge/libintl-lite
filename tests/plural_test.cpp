#include "libintl.h"

#include <string>

#include <stdio.h>
#include <string.h>

static int failures = 0;

static void check(const char* actual, const char* expected, const char* what)
{
	if (!actual || strcmp(actual, expected) != 0)
	{
		fprintf(stderr, "FAIL: %s: expected \"%s\", got \"%s\"\n", what, expected, actual ? actual : "(null)");
		++failures;
	}
}

static void checkPlural(const char* domain, unsigned long n, const char* expected)
{
	const std::string what = std::string(domain) + " n=" + std::to_string(n);
	check(dngettext(domain, "%1 file", "%1 files", n), expected, what.c_str());
}

static bool load(const char* moFilesDir, const char* domain)
{
	const std::string path = std::string(moFilesDir) + "/" + domain + ".mo";
	if (!loadMessageCatalog(domain, path.c_str()))
	{
		fprintf(stderr, "FAIL: could not load %s\n", path.c_str());
		++failures;
		return false;
	}
	return true;
}

int main(int argc, char** argv)
{
	if (argc != 2)
	{
		fprintf(stderr, "usage: %s <directory with .mo files>\n", argv[0]);
		return 1;
	}
	const char* moFilesDir = argv[1];

	if (load(moFilesDir, "de"))
	{
		checkPlural("de", 0, "%1 Dateien");
		checkPlural("de", 1, "%1 Datei");
		checkPlural("de", 2, "%1 Dateien");

		// lookups of the singular form only return the first plural form
		check(dgettext("de", "%1 file"), "%1 Datei", "de singular lookup");
		// other messages sorted around the plural message are still found
		check(dgettext("de", "%1 file found"), "%1 Datei gefunden", "de message next to plural message");
		check(dgettext("de", "Open"), "Öffnen", "de regular message");

		// context is prefixed to the original string, separated by EOT
		check(dngettext("de", "storage\004One folder", "%1 folders", 1), "Ein Ordner", "de context n=1");
		check(dngettext("de", "storage\004One folder", "%1 folders", 3), "%1 Ordner", "de context n=3");

		// untranslated messages return the original strings, not copies of them
		const char* missing = "missing";
		const char* missingPlural = "missings";
		if (dngettext("de", missing, missingPlural, 1) != missing || dngettext("de", missing, missingPlural, 2) != missingPlural)
		{
			fprintf(stderr, "FAIL: untranslated plural message\n");
			++failures;
		}
	}

	if (load(moFilesDir, "pl"))
	{
		checkPlural("pl", 0, "%1 plików");
		checkPlural("pl", 1, "%1 plik");
		checkPlural("pl", 2, "%1 pliki");
		checkPlural("pl", 4, "%1 pliki");
		checkPlural("pl", 5, "%1 plików");
		checkPlural("pl", 12, "%1 plików");
		checkPlural("pl", 22, "%1 pliki");
		checkPlural("pl", 112, "%1 plików");
	}

	if (load(moFilesDir, "ar"))
	{
		checkPlural("ar", 0, "zero");
		checkPlural("ar", 1, "one");
		checkPlural("ar", 2, "two");
		checkPlural("ar", 3, "few");
		checkPlural("ar", 10, "few");
		checkPlural("ar", 11, "many");
		checkPlural("ar", 99, "many");
		checkPlural("ar", 100, "other");
		checkPlural("ar", 103, "few");
	}

	if (load(moFilesDir, "ja"))
	{
		checkPlural("ja", 1, "%1 ファイル");
		checkPlural("ja", 7, "%1 ファイル");
	}

	// without plural form information, the rule for English is used like by GNU gettext
	if (load(moFilesDir, "noheader"))
	{
		checkPlural("noheader", 1, "singular");
		checkPlural("noheader", 2, "plural");
	}

	// the default domain is used for ngettext()
	textdomain("pl");
	check(ngettext("%1 file", "%1 files", 5), "%1 plików", "ngettext with default domain");

	closeAllLoadedMessageCatalogs();

	if (failures == 0)
	{
		printf("All tests passed.\n");
		return 0;
	}
	return 1;
}
