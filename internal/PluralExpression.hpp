#ifndef LIBINTL_INTERNAL_PLURALEXPRESSION_HPP_
#define LIBINTL_INTERNAL_PLURALEXPRESSION_HPP_

#include <vector>

#include <string.h>

namespace libintllite
{

namespace internal
{

// Evaluates the "plural=" expression of a message catalog's "Plural-Forms" header,
// for example "(n==1 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2)".
// This is the subset of C supported by GNU gettext: the variable n, unsigned integer
// numbers, parentheses and the operators ! * / % + - < <= > >= == != && || ?:
class PluralExpression
{
private:
	enum Operation
	{
		VARIABLE_N,
		NUMBER,
		NOT,
		MULTIPLY,
		DIVIDE,
		MODULO,
		ADD,
		SUBTRACT,
		LESS,
		LESS_OR_EQUAL,
		GREATER,
		GREATER_OR_EQUAL,
		EQUAL,
		NOT_EQUAL,
		AND,
		OR,
		CONDITIONAL
	};

	struct Node
	{
		Operation operation;
		unsigned long number;
		int operands[3];
	};

	// All nodes of the syntax tree.
	std::vector<Node> nodes;
	int root;

	// Parser state, only used while parsing.
	const char* parsePos;

	int addNode(Operation operation, int operand1 = -1, int operand2 = -1, int operand3 = -1, unsigned long number = 0)
	{
		Node node;
		node.operation = operation;
		node.number = number;
		node.operands[0] = operand1;
		node.operands[1] = operand2;
		node.operands[2] = operand3;
		this->nodes.push_back(node);
		return static_cast<int>(this->nodes.size()) - 1;
	}

	void skipWhitespace()
	{
		while (*this->parsePos == ' ' || *this->parsePos == '\t' || *this->parsePos == '\n' || *this->parsePos == '\r')
		{
			++this->parsePos;
		}
	}

	// Consumes token, if it is the next one in the input.
	bool consume(const char* token)
	{
		skipWhitespace();
		const size_t tokenLength = strlen(token);
		if (strncmp(this->parsePos, token, tokenLength) != 0)
		{
			return false;
		}
		// don't mistake "<=" for "<", or "==" for "=" etc.
		if (tokenLength == 1 && (token[0] == '<' || token[0] == '>' || token[0] == '!') && this->parsePos[1] == '=')
		{
			return false;
		}
		this->parsePos += tokenLength;
		return true;
	}

	// Each of the following returns the index of the parsed node, or -1 on syntax errors.

	int parseConditional()
	{
		const int condition = parseOr();
		if (condition < 0 || !consume("?"))
		{
			return condition;
		}
		const int ifTrue = parseConditional();
		if (ifTrue < 0 || !consume(":"))
		{
			return -1;
		}
		const int ifFalse = parseConditional();
		if (ifFalse < 0)
		{
			return -1;
		}
		return addNode(CONDITIONAL, condition, ifTrue, ifFalse);
	}

	int parseOr()
	{
		int lhs = parseAnd();
		while (lhs >= 0 && consume("||"))
		{
			const int rhs = parseAnd();
			lhs = rhs < 0 ? -1 : addNode(OR, lhs, rhs);
		}
		return lhs;
	}

	int parseAnd()
	{
		int lhs = parseEquality();
		while (lhs >= 0 && consume("&&"))
		{
			const int rhs = parseEquality();
			lhs = rhs < 0 ? -1 : addNode(AND, lhs, rhs);
		}
		return lhs;
	}

	int parseEquality()
	{
		int lhs = parseRelation();
		while (lhs >= 0)
		{
			Operation operation;
			if (consume("=="))
			{
				operation = EQUAL;
			}
			else if (consume("!="))
			{
				operation = NOT_EQUAL;
			}
			else
			{
				break;
			}
			const int rhs = parseRelation();
			lhs = rhs < 0 ? -1 : addNode(operation, lhs, rhs);
		}
		return lhs;
	}

	int parseRelation()
	{
		int lhs = parseAdditive();
		while (lhs >= 0)
		{
			Operation operation;
			if (consume("<="))
			{
				operation = LESS_OR_EQUAL;
			}
			else if (consume(">="))
			{
				operation = GREATER_OR_EQUAL;
			}
			else if (consume("<"))
			{
				operation = LESS;
			}
			else if (consume(">"))
			{
				operation = GREATER;
			}
			else
			{
				break;
			}
			const int rhs = parseAdditive();
			lhs = rhs < 0 ? -1 : addNode(operation, lhs, rhs);
		}
		return lhs;
	}

	int parseAdditive()
	{
		int lhs = parseMultiplicative();
		while (lhs >= 0)
		{
			Operation operation;
			if (consume("+"))
			{
				operation = ADD;
			}
			else if (consume("-"))
			{
				operation = SUBTRACT;
			}
			else
			{
				break;
			}
			const int rhs = parseMultiplicative();
			lhs = rhs < 0 ? -1 : addNode(operation, lhs, rhs);
		}
		return lhs;
	}

	int parseMultiplicative()
	{
		int lhs = parseUnary();
		while (lhs >= 0)
		{
			Operation operation;
			if (consume("*"))
			{
				operation = MULTIPLY;
			}
			else if (consume("/"))
			{
				operation = DIVIDE;
			}
			else if (consume("%"))
			{
				operation = MODULO;
			}
			else
			{
				break;
			}
			const int rhs = parseUnary();
			lhs = rhs < 0 ? -1 : addNode(operation, lhs, rhs);
		}
		return lhs;
	}

	int parseUnary()
	{
		if (consume("!"))
		{
			const int operand = parseUnary();
			return operand < 0 ? -1 : addNode(NOT, operand);
		}
		return parsePrimary();
	}

	int parsePrimary()
	{
		if (consume("("))
		{
			const int expression = parseConditional();
			if (expression < 0 || !consume(")"))
			{
				return -1;
			}
			return expression;
		}
		if (consume("n"))
		{
			return addNode(VARIABLE_N);
		}

		skipWhitespace();
		if (*this->parsePos < '0' || *this->parsePos > '9')
		{
			return -1;
		}
		unsigned long number = 0;
		while (*this->parsePos >= '0' && *this->parsePos <= '9')
		{
			number = number * 10 + static_cast<unsigned long>(*this->parsePos - '0');
			++this->parsePos;
		}
		return addNode(NUMBER, -1, -1, -1, number);
	}

	unsigned long evaluateNode(int index, unsigned long n) const
	{
		const Node& node = this->nodes[index];
		switch (node.operation)
		{
		case VARIABLE_N:
			return n;
		case NUMBER:
			return node.number;
		case NOT:
			return !evaluateNode(node.operands[0], n);
		case CONDITIONAL:
			return evaluateNode(node.operands[0], n) ? evaluateNode(node.operands[1], n) : evaluateNode(node.operands[2], n);
		case AND:
			return evaluateNode(node.operands[0], n) && evaluateNode(node.operands[1], n);
		case OR:
			return evaluateNode(node.operands[0], n) || evaluateNode(node.operands[1], n);
		default:
			break;
		}

		const unsigned long lhs = evaluateNode(node.operands[0], n);
		const unsigned long rhs = evaluateNode(node.operands[1], n);
		switch (node.operation)
		{
		case MULTIPLY:
			return lhs * rhs;
		case DIVIDE:
			return rhs == 0 ? 0 : lhs / rhs;
		case MODULO:
			return rhs == 0 ? 0 : lhs % rhs;
		case ADD:
			return lhs + rhs;
		case SUBTRACT:
			return lhs - rhs;
		case LESS:
			return lhs < rhs;
		case LESS_OR_EQUAL:
			return lhs <= rhs;
		case GREATER:
			return lhs > rhs;
		case GREATER_OR_EQUAL:
			return lhs >= rhs;
		case EQUAL:
			return lhs == rhs;
		case NOT_EQUAL:
			return lhs != rhs;
		default:
			return 0;
		}
	}

public:
	PluralExpression() :
			root(-1),
			parsePos(NULL)
	{
	}

	// Parses expression, which ends at the end of the string or at a ';'.
	// Returns false on syntax errors, the expression is empty then.
	// Does not throw exceptions other than std::bad_alloc!
	bool parse(const char* expression)
	{
		this->nodes.clear();
		this->parsePos = expression;
		this->root = parseConditional();
		skipWhitespace();
		const bool success = this->root >= 0 && (*this->parsePos == '\0' || *this->parsePos == ';');
		if (!success)
		{
			this->nodes.clear();
			this->root = -1;
		}
		this->parsePos = NULL;
		return success;
	}

	// Returns the index of the plural form to use for n.
	unsigned long evaluate(unsigned long n) const
	{
		if (this->root < 0)
		{
			// default of GNU gettext in the absence of plural form information
			return n != 1;
		}
		return evaluateNode(this->root, n);
	}
};

} // namespace internal

} // namespace libintllite

#endif // LIBINTL_INTERNAL_PLURALEXPRESSION_HPP_
